// Generate a Playwright .spec.ts for one tour, written directly into the
// target module's own tests/02-business/ folder.
//
// The spec navigates to the Odoo backend, then walks each step: locate the
// trigger, wait for it, screenshot the state the user acts on (with the target
// outlined), then perform the mapped action. Screenshots feed the manuals.
//
// The generated spec imports from this repo's shared fixtures (not
// `@playwright/test` directly) and carries `@module:<domain> @step:business
// @e2e` tags, so it's a normal citizen of the framework: it shows up in
// `npm test`, the master report, and passes `/review-tests` like any other
// spec. It executes via the MAIN suite's own runner/auth (not a separate
// login flow), so SHOT_DIR is a repo-root-relative path.
import { selectorToLocator, actionFor, jsString } from "./translate.mjs";
import { shotFile, shotDirFromRepoRoot } from "./names.mjs";

const START_PATH = process.env.ODOO_START_PATH || "/web";

/**
 * @param {object} tour normalized tour (from loadTours)
 * @param {string} domain target module (e.g. "hr")
 * @param {string} [step] test step the spec belongs to (default "business")
 * @returns {{ filename: string, source: string, todos: Array<{step:number,msg:string}> }}
 */
export function genSpec(tour, domain, step = "business") {
  const total = tour.steps.length;
  const dir = shotDirFromRepoRoot(tour.slug);
  const allTodos = [];
  const lines = [];

  lines.push(`// AUTO-GENERATED by tour2playwright from a Tour Recorder export.`);
  lines.push(`// Source tour: ${tour.name}`);
  lines.push(`// Regenerate with:  npm run gen -- ${domain} <export.json>  (from tools/tour2playwright/)`);
  lines.push(`// Review any "TODO" markers below — Odoo tour selectors/actions`);
  lines.push(`// don't all map 1:1 onto Playwright.`);
  lines.push(`import { test, expect } from "../../../../core/fixtures/index";`);
  lines.push(`import { uniqueName, uniqueEmail, uniqueRef } from "../../../../core/utils/RandomDataGenerator";`);
  lines.push(`import type { Page, Locator } from "@playwright/test";`);
  lines.push(`import fs from "node:fs";`);
  lines.push(``);
  lines.push(`const SHOT_DIR = ${jsString(dir)};`);
  lines.push(``);
  lines.push(`// Screenshot the current page with the target element outlined.`);
  lines.push(`async function shot(page: Page, loc: Locator, file: string) {`);
  lines.push(`  try {`);
  lines.push(`    await loc.scrollIntoViewIfNeeded({ timeout: 5000 });`);
  lines.push(`    await loc.evaluate((el) => el.setAttribute("data-t2p", "1"));`);
  lines.push(`    await page.addStyleTag({`);
  lines.push(`      content: '[data-t2p="1"]{outline:3px solid #e01e5a !important;outline-offset:2px !important;}',`);
  lines.push(`    });`);
  lines.push(`  } catch {}`);
  lines.push(`  fs.mkdirSync(SHOT_DIR, { recursive: true });`);
  lines.push(`  await page.screenshot({ path: \`\${SHOT_DIR}/\${file}\` });`);
  lines.push(`  try { await loc.evaluate((el) => el.removeAttribute("data-t2p")); } catch {}`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`test.describe(${jsString(`${tour.name} @module:${domain} @step:${step}${step === "business" ? " @e2e" : ""}`)}, () => {`);
  // Wide viewport: at 1280px Odoo folds navbar section menus into the overflow "+" menu, hiding them.
  lines.push(`  test.use({ viewport: { width: 1920, height: 1080 }, actionTimeout: 15_000 });`);
  lines.push(`  test(${jsString(tour.name)}, async ({ page }) => {`);
  lines.push(`    test.setTimeout(${Math.max(120, total * 40) * 1000});`);
  lines.push(`    await page.goto(${jsString(START_PATH)});`);
  lines.push(`    // Odoo keeps persistent long-polling/websocket connections open for`);
  lines.push(`    // real-time notifications, so "networkidle" never naturally resolves —`);
  lines.push(`    // bound it explicitly or it silently eats the whole test timeout as its`);
  lines.push(`    // fallback ceiling before its own .catch() ever fires.`);
  lines.push(`    await page.waitForLoadState("networkidle", { timeout: 10_000 }).catch(() => {});`);
  lines.push(``);

  const stepName = step; // the loop below shadows `step`
  for (const step of tour.steps) {
    let { expr, todos: selTodos } = selectorToLocator(step.trigger);
    if (stepName === "archive") {
      // Cleanup tours must hit the records the search found, not whatever is
      // first: open a non-empty group, and pick the action by its label rather
      // than its position in the menu.
      if (/^\.o_list_view (tr)?\.?o_group_header|^\.o_list_view tr\.o_group_header/.test((step.trigger || "").trim())) {
        expr = `page.locator(".o_list_view .o_group_header").filter({ hasNotText: "(0)" })`;
      } else if (/^\.o_cp_action_menus \.dropdown-item:(nth-child\(\d+\)|last-child)$/.test((step.trigger || "").trim()) && step.title) {
        expr = `page.locator(".o_cp_action_menus .dropdown-item").filter({ hasText: ${jsString(step.title)} })`;
      }
    }
    const { code, todos: actTodos } = actionFor(expr, step);
    const file = shotFile(step.number, total);
    const label = `${String(step.number).padStart(2, "0")}. ${step.title || step.trigger || "step"}`;

    for (const t of [...selTodos, ...actTodos]) {
      allTodos.push({ step: step.number, msg: t });
    }

    // Archive-step tours are cleanup for records the earlier tours created
    // (names come from uniqueName(), i.e. "[TEST] ..."): search for those only,
    // and skip rather than touch real data when none exist.
    const isCleanupSearch =
      stepName === "archive" && /o_searchview_input/.test(step.trigger || "") && /press/i.test(step.run || "");
    const cleanupCode = isCleanupSearch
      ? ['loc.fill("[TEST] Tour");', 'loc.press("Enter");',
         'await page.waitForTimeout(1500);',
         'if (!(await page.locator(".o_data_row, .o_group_header, .o_kanban_record").first().isVisible().catch(() => false))) test.skip(true, "No test records to clean up");']
          .map((l) => (l.startsWith("loc.") ? "await " + l : l)).join("\n")
      : null;
    // A last "Click anywhere to finish/continue" step only ends the tour. The
    // screenshot above already covers it, and clicking a big pivot or list
    // header can hang on actionability checks, so don't click.
    const endsTour =
      step.number === total && /click\b.*\b(finish|continue)\b/i.test(step.content || "") &&
      /^click$/i.test(String(step.run ?? "click").trim());
    const finalCode = endsTour ? "// (click skipped: only ends the tour)" : (cleanupCode ?? code);
    // Indent multi-line action code (the "manual" case spans two lines).
    const actionCode = finalCode
      .split("\n")
      .map((l) => `      ${l}`)
      .join("\n");

    lines.push(`    await test.step(${jsString(label)}, async () => {`);
    for (const t of [...selTodos, ...actTodos]) {
      lines.push(`      // TODO: ${t}`);
    }
    // `.first()` guards against Odoo selectors that match several nodes
    // (Playwright's strict mode would otherwise throw).
    // `:visible` skips hidden duplicates (e.g. Odoo renders a second, hidden
    // control-panel button), which `.first()` alone would pick and never see.
    // Timeout is generous (45s, not Playwright's usual default) because
    // staging/dev Odoo.sh databases can be slow to wake from idle on the
    // first real request — the element itself is often correct, it just
    // hasn't finished rendering yet.
    const trig = (step.trigger || "").trim();
    if (stepName === "business" && trig === ".o_kanban_view .o_kanban_record") {
      // The tour clicks "the" employee card; on a shared database that is a
      // real person. Work on the test employees the earlier tours created.
      lines.push(`      const sv = page.locator(".o_control_panel .o_searchview_input").first();`);
      lines.push(`      await sv.fill("[TEST] Tour");`);
      lines.push(`      await sv.press("Enter");`);
      lines.push(`      await page.waitForTimeout(1500);`);
      lines.push(`      if (!(await page.locator(".o_kanban_record").first().isVisible().catch(() => false))) test.skip(true, "No test records to work on");`);
    }
    lines.push(`      const loc = (${expr}).and(page.locator(":visible")).first();`);
    // Action buttons (Compute, Approve, Mark as paid...) only exist in some
    // record states, and these tours move records forward, so a record that is
    // already past that state is a missing precondition, not a failure.
    const stateButton =
      stepName === "business" &&
      (/^button\[name="[^"]+"\]$/.test(trig) || trig === '[name="input_line_ids"] .o_field_x2many_list_row_add a');
    if (stateButton) {
      lines.push(`      if (!(await loc.waitFor({ state: "visible", timeout: 8000 }).then(() => true, () => false))) {`);
      lines.push(`        test.skip(true, ${jsString(`${step.title || trig} is not available: the record is not in the required state`)});`);
      lines.push(`      }`);
    } else if (stepName === "archive" && /^\.o_cp_action_menus \.dropdown-item/.test((step.trigger || "").trim())) {
      // The Actions menu can close under us while the record is still loading:
      // re-open it until the item shows.
      lines.push(`      await expect(async () => {`);
      lines.push(`        if (!(await loc.isVisible())) await page.locator(".o_cp_action_menus .dropdown-toggle").first().click();`);
      lines.push(`        await expect(loc).toBeVisible({ timeout: 3000 });`);
      lines.push(`      }).toPass({ timeout: 45000 });`);
    } else {
      lines.push(`      await loc.waitFor({ state: "visible", timeout: 45000 });`);
    }
    lines.push(`      await shot(page, loc, ${jsString(file)});`);
    lines.push(actionCode);
    lines.push(`    });`);
    lines.push(``);
  }

  lines.push(`  });`);
  lines.push(`});`);
  lines.push(``);

  return {
    filename: `${domain}.${tour.slug}-tour.spec.ts`,
    source: lines.join("\n"),
    todos: allTodos,
  };
}
